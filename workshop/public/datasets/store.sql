       DATE '2025-01-03' + (g * 37) % 360,
       CASE
         WHEN g % 10 = 0 THEN 'cancelled'
         WHEN g % 10 IN (1, 2) THEN 'pending'
         WHEN g % 10 IN (3, 4) THEN 'paid'
         WHEN g % 10 IN (5, 6) THEN 'shipped'
         ELSE 'delivered'
       END
FROM generate_series(1, 90) AS g;

